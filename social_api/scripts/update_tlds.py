#!/usr/bin/env python3
"""Regenerate the top-level-domain list the link rule reads, from IANA's file.

Usage:
    curl -o /tmp/tlds.txt https://data.iana.org/TLD/tlds-alpha-by-domain.txt
    python -I scripts/update_tlds.py /tmp/tlds.txt

Writes two files that must stay equal (test_link_rule.py checks they do):
    app/constants/tlds.py                         — the server's copy
    ../social_flutter/lib/core/text/tlds.dart     — the app's copy

Each holds every TLD in lower case, plus the Unicode spelling of each
internationalised one (xn--fiqs8s → 中国), so a site name written in its own
script is recognised too. The file is IANA's plain list; nothing in it is
executed, and every line is checked to be a DNS label before it is used.
"""
import re
import sys
from pathlib import Path

API = Path(__file__).resolve().parents[1]
PY_OUT = API / "app" / "constants" / "tlds.py"
DART_OUT = API.parent / "social_flutter" / "lib" / "core" / "text" / "tlds.dart"

_LABEL = re.compile(r"^(?:[a-z]{2,63}|xn--[a-z0-9-]{1,59})$")


def read_iana(path: Path) -> tuple[str, list[str]]:
    lines = path.read_text("ascii").splitlines()
    header = re.match(r"^# Version (\d+)", lines[0])
    if header is None:
        raise SystemExit("not IANA's tlds-alpha-by-domain.txt: no '# Version' line")
    tlds: set[str] = set()
    for line in lines[1:]:
        label = line.strip().lower()
        if not label:
            continue
        if not _LABEL.match(label):
            raise SystemExit(f"unexpected line in the TLD list: {line!r}")
        tlds.add(label)
        if label.startswith("xn--"):
            tlds.add(label[4:].encode("ascii").decode("punycode").lower())
    return header.group(1), sorted(tlds)


def write_python(version: str, tlds: list[str]) -> None:
    body = "".join(f"    {t!r},\n" for t in tlds)
    PY_OUT.write_text(
        '"""constants/tlds.py — every top-level domain IANA lists, for the link\n'
        "rule's bare site names (validators/links.py).\n\n"
        "Generated by scripts/update_tlds.py from IANA's tlds-alpha-by-domain.txt;\n"
        "never edit by hand. The app's lib/core/text/tlds.dart is generated beside it,\n"
        'and test_link_rule.py holds the two equal.\n"""\n\n'
        f'IANA_TLDS_VERSION = "{version}"\n\n'
        "IANA_TLDS = frozenset({\n" + body + "})\n",
        "utf-8",
    )


def write_dart(version: str, tlds: list[str]) -> None:
    def quoted(t: str) -> str:
        return "'" + t.replace("\\", "\\\\").replace("'", "\\'") + "'"

    body = "".join(f"  {quoted(t)},\n" for t in tlds)
    DART_OUT.parent.mkdir(parents=True, exist_ok=True)
    DART_OUT.write_text(
        "// core/text/tlds.dart — every top-level domain IANA lists, for the link\n"
        "// rule's bare site names (link_rule.dart).\n"
        "//\n"
        "// Generated by social_api/scripts/update_tlds.py from IANA's\n"
        "// tlds-alpha-by-domain.txt; never edit by hand. The server's\n"
        "// app/constants/tlds.py is generated beside it, and test_link_rule.py\n"
        "// holds the two equal.\n\n"
        f"const ianaTldsVersion = '{version}';\n\n"
        "const ianaTlds = <String>{\n" + body + "};\n",
        "utf-8",
    )


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    version, tlds = read_iana(Path(sys.argv[1]))
    write_python(version, tlds)
    write_dart(version, tlds)
    print(f"{len(tlds)} names from IANA version {version} written to "
          f"{PY_OUT.relative_to(API.parent)} and {DART_OUT.relative_to(API.parent)}.")


if __name__ == "__main__":
    main()
