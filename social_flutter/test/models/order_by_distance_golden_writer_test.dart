// order_by_distance_golden.dart from this machine's answers. Run it once, on
// purpose, when an answer is meant to change:
//
//   flutter test --dart-define=UPDATE_ORDER_GOLDEN=true \
//     test/models/order_by_distance_golden_writer_test.dart
//
// Skipped otherwise. The VM only: the browser cannot write files.
@TestOn('vm')
library;

import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

import '../support/order_by_distance_days.dart';

const _update = bool.fromEnvironment('UPDATE_ORDER_GOLDEN');

void main() {
  test('writes the Order by distance golden file', () async {
    final lines = await orderGoldenOf(orderDays());
    final out = StringBuffer()
      ..writeln('// test/models/order_by_distance_golden.dart — GENERATED by')
      ..writeln('// order_by_distance_golden_writer_test.dart; never by hand.')
      ..writeln('// Each fixed day of order_by_distance_days.dart, each choice')
      ..writeln('// (S/s start kept/free, E/e end, L/l segments): the order')
      ..writeln('// as the old track numbers, with metres before > after.')
      ..writeln()
      ..writeln('const orderGolden = <String, String>{');
    for (final MapEntry(:key, :value) in lines.entries) {
      out.writeln("  '$key': '$value',");
    }
    out.writeln('};');
    File('test/models/order_by_distance_golden.dart')
        .writeAsStringSync(out.toString());
  },
      skip: _update
          ? false
          : 'Writes the golden on purpose: '
              '--dart-define=UPDATE_ORDER_GOLDEN=true');
}
