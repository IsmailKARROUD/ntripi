class Country {
  final String code;
  final String name;
  final String nameFr;
  final String flag;

  const Country(this.code, this.name, this.nameFr, this.flag);

  /// Display name for the given language code ('fr' → French, else English).
  String localizedName(String langCode) => langCode == 'fr' ? nameFr : name;
}

Country? countryByCode(String code) {
  final upper = code.toUpperCase();
  for (final c in kCountries) {
    if (c.code == upper) return c;
  }
  return null;
}

