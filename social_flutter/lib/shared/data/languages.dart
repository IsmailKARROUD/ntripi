class Language {
  final String code;
  final String name;

  const Language(this.code, this.name);
}

Language? languageByCode(String code) {
  final upper = code.toUpperCase();
  for (final l in kLanguages) {
    if (l.code == upper) return l;
  }
  return null;
}

