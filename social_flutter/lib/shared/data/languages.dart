class Language {
  final String code;
  final String name;
  final String nameFr;

  const Language(this.code, this.name, this.nameFr);

  /// Display name for the given language code ('fr' → French, else English).
  String localizedName(String langCode) => langCode == 'fr' ? nameFr : name;
}

Language? languageByCode(String code) {
  final upper = code.toUpperCase();
  for (final l in kLanguages) {
    if (l.code == upper) return l;
  }
  return null;
}

